def raster(vertices):
    out=np.zeros((240,400,3),np.float32)
    for triangle in vertices.reshape(-1,3):
        p=triangle['position'][:,:2];lo=np.maximum(np.floor(p.min(axis=0)).astype(int),0);hi=np.minimum(np.ceil(p.max(axis=0)).astype(int),[399,239])
        if np.any(lo>hi):continue
